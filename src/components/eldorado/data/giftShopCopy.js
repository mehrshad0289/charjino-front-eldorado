/* Clone-page defaults only (`/xbox-game-pass`, banner fallback). Live `/gift-card/{platform}` reads published hub tabs from the API. */

export function giftShopBannerTabs(platform, shopHref) {
  const id = normalizeGiftPlatform(platform);
  const giftHref = shopHref || giftShopHref(id === "playstation" ? "playstation" : id);
  if (id === "playstation") {
    return [
      { key: "Accounts", label: FA.accounts, href: SHOP_ACCOUNTS_HREF },
      { key: "Subscription", label: FA.subscription, href: "/playstation-plus" },
      { key: "Gift cards", label: FA.giftCards, href: giftHref || "/gift-card/playstation" },
    ];
  }
  if (id === "xbox") {
    return [
      { key: "Accounts", label: FA.accounts, href: SHOP_ACCOUNTS_HREF },
      { key: "Game Pass", label: FA.gamePass, href: "/xbox-game-pass" },
      { key: "Gift cards", label: FA.giftCards, href: giftHref || "/gift-card/xbox" },
    ];
  }
  return [
    { key: "Accounts", label: FA.accounts, href: SHOP_ACCOUNTS_HREF },
    { key: "Gift cards", label: FA.giftCards, href: giftHref },
  ];
}

export function playstationHubTabs() {
  return giftShopBannerTabs("playstation", "/gift-card/playstation");
}

